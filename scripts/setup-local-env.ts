/**
 * Writes .env.local for the LOCAL Supabase stack (npm run local:start).
 * Reads URLs and keys from `supabase status`; never use these keys in production.
 *
 *   npm run local:env
 */
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

function status(): Record<string, string> {
  let raw: string;
  try {
    raw = execSync("npx supabase status -o env", { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
  } catch {
    console.error("\n✖ The local Supabase stack is not running. Start it with: npm run local:start\n");
    process.exit(1);
  }
  const out: Record<string, string> = {};
  for (const line of raw.split(/\r?\n/)) {
    const m = /^([A-Z_]+)="?(.*?)"?$/.exec(line.trim());
    if (m) out[m[1]] = m[2];
  }
  return out;
}

const s = status();
const url = s.API_URL;
const publishable = s.PUBLISHABLE_KEY || s.ANON_KEY;
const secret = s.SERVICE_ROLE_KEY || s.SECRET_KEY;
if (!url || !publishable || !secret) {
  console.error("\n✖ Could not read API_URL / keys from `supabase status`.\n");
  process.exit(1);
}

// Keep any optional values the developer already set (Resend etc.).
const existing = existsSync(".env.local") ? readFileSync(".env.local", "utf8") : "";
const keep = existing
  .split(/\r?\n/)
  .filter((l) => /^(RESEND_API_KEY|CONTACT_EMAIL|RESEND_FROM_EMAIL|WHATSAPP_PHONE)=/.test(l));

const env = [
  "# Generated by `npm run local:env` for the LOCAL Supabase stack.",
  `NEXT_PUBLIC_SUPABASE_URL=${url}`,
  `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${publishable}`,
  `SUPABASE_SERVICE_ROLE_KEY=${secret}`,
  "NEXT_PUBLIC_SITE_URL=http://localhost:3000",
  "",
  "# Local admin (temporary password; you will be asked to change it at first sign-in)",
  "ADMIN_EMAIL=admin@example.com",
  "ADMIN_PASSWORD=ChangeMe-Local-2026",
  "",
  ...keep,
  "",
].join("\n");

writeFileSync(".env.local", env);
console.log("✓ .env.local written for the local stack");
console.log(`  API: ${url}`);
console.log("  Next: npm run admin:create, then npm run dev");
